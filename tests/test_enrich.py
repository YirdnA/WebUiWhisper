def test_transcript_sha256_stable():
    payload = {"segments": [{"text": "a"}, {"text": "b"}]}
    s1 = enrich._transcript_sha256(payload)
    s2 = enrich._transcript_sha256(payload)
    assert s1 == s2
    payload2 = {"segments": [{"text": "a"}, {"text": "different"}]}
    assert s1 != enrich._transcript_sha256(payload2)



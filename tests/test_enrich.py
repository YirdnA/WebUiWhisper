def test_render_md_minimal_section_ordering():
    sidecar = {
        "patterns": {
            "title": "Hello",
            "summary_tldr": "One line",
            "summary": "Para.",
            "main_ideas": ["a", "b"],
            "todos": [{"who": "spk_0", "what": "do thing", "anchor_sec": 12.5}],
            "hashtags": ["#tag"],
        },
        "model": "qwen2.5:7b",
        "ran_at": "2026-05-20T00:00:00Z",
        "transcript_sha256": "deadbeef",
    }
    md = render_enrich_md(sidecar, with_timecodes=False)
    # Section order
    i_title = md.index("# Hello")
    i_summary = md.index("## Summary")
    i_ideas = md.index("## Main Ideas")
    i_todos = md.index("## Todos")
    assert i_title < i_summary < i_ideas < i_todos
    # No timecode prefix in prose mode
    assert "[00:00:12]" not in md



@pytest.mark.asyncio
async def test_enrich_lock_serialises():
    """Two tasks waiting on the lock run one-after-another, never concurrently."""
    state = {"running": 0, "max_concurrent": 0}

    async def job(name: str):
        async with enrich_lock.acquire(name):
            state["running"] += 1
            state["max_concurrent"] = max(state["max_concurrent"], state["running"])
            await asyncio.sleep(0.03)
            state["running"] -= 1

    await asyncio.gather(job("a"), job("b"), job("c"))
    assert state["max_concurrent"] == 1


@pytest.mark.asyncio
async def test_enrich_runs_patterns_with_mocked_ollama(tmp_settings):
    """End-to-end: enrich() drives the patterns and returns a sidecar dict."""
    payload = {
        "language": "en",
        "segments": [
            {"speaker": "spk_0", "start_time": "00:00:00.000",
             "start_sec": 0.0, "end_sec": 5.0,
             "text": "We will ship Tuesday."},
        ],
    }

    async def fake_chat(self, prompt, json_mode=True):
        # Each pattern responds with a minimal JSON envelope.
        return json.dumps({"title": "Demo"})

    async def fake_embed(self, text):
        return [0.1, 0.2, 0.3]

    with patch.object(enrich.OllamaClient, "chat", new=fake_chat), \
         patch.object(enrich.OllamaClient, "embeddings", new=fake_embed):
        sidecar = await enrich.enrich(
            payload,
            enabled={"title", enrich.EMBEDDING_KEY},
            model="qwen2.5:7b",
            embed_model="nomic-embed-text",
            settings=tmp_settings,
            source_filename="demo.wav",
        )

    assert sidecar["patterns"]["title"] == "Demo"
    assert sidecar["embedding"]["whole"] == [0.1, 0.2, 0.3]
    assert sidecar["transcript_sha256"]
    assert sidecar["model"] == "qwen2.5:7b"


@pytest.mark.asyncio
async def test_enrich_records_failures_per_pattern(tmp_settings):
    payload = {"language": "en", "segments": [{"text": "x", "start_sec": 0}]}
    call_count = {"n": 0}

    async def flaky_chat(self, prompt, json_mode=True):
        call_count["n"] += 1
        if call_count["n"] == 1:
            raise enrich.OllamaError("boom")
        return json.dumps({"summary_tldr": "ok"})

    with patch.object(enrich.OllamaClient, "chat", new=flaky_chat):
        sidecar = await enrich.enrich(
            payload,
            enabled={"title", "summary_tldr"},
            model="qwen2.5:7b",
            embed_model="nomic-embed-text",
            settings=tmp_settings,
            source_filename="demo.wav",
        )

    assert "title" in sidecar["failures"]
    assert sidecar["patterns"]["summary_tldr"] == "ok"

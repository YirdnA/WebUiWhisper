def test_prompt_has_required_fields():
    # `named_entities` and `quotes` intentionally preserve native script
    # regardless of transcript language, so neither prompt carries the
    # {language_name} placeholder.
    # Sentiment uses a fixed English label set; named_entities and quotes
    # preserve native script; none carry a {language_name} placeholder.
    NO_LANG = {"named_entities", "quotes", "sentiment"}
    for key, meta in enrich.PROMPTS.items():
        assert meta["key"] == key
        assert meta["description"], f"{key} missing description"
        assert "{transcript_text}" in meta["body"], f"{key} missing transcript placeholder"
        if key not in NO_LANG:
            assert "{language_name}" in meta["body"], f"{key} missing language placeholder"


